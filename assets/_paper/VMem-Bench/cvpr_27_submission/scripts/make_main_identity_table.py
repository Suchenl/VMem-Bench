#!/usr/bin/env python3
"""Render compact historical-continuity results from frozen scorer JSON.

Policies are rows, with the absolute no-memory baseline first and deltas below.
Column-header N counts eligible events, not policy-specific detected pairs.
"""
import json
from pathlib import Path
from make_identity_tables import diff_cell

PAPER = Path(__file__).resolve().parents[1]
TABLES = PAPER / 'tables' / 'experiments'


def main():
    cells = json.loads((TABLES/'trackb_identity_embed.json').read_text())['modalities']['dino_crop']['cells']
    strata = [('main|all', 'All returns'), ('main|character', 'Characters'),
              ('main|prop', 'Props'), ('transform_ge30|all', 'Changed')]
    policies = [('text_frame','Text-frame'), ('seg_uniform','Seg+uniform'),
                ('seg_dinokey','Seg+DINO-key'), ('seg_frame_clean','Seg+frame'),
                ('retr_oracle','Last-seen')]
    lines = [
        '% Generated by scripts/make_main_identity_table.py; do not edit by hand.',
        r'\begin{table}[t]', r'\centering',
        r'\caption{\textbf{Historical appearance continuity.} DINOv3 crop cosine: no-memory means and policy deltas ($\Delta$). Bold: paired story-bootstrap 95\% CI excludes zero. $N$ counts eligible events; detected pairs vary by policy. Changed: characters returning after $\geq$30 segments; similarity can reward obsolete looks.}',
        r'\label{tab:main-identity}', r'\footnotesize',
        r'\setlength{\tabcolsep}{2.5pt}', r'\begin{tabular}{@{}lrrrr@{}}', r'\toprule',
        'Policy & ' + ' & '.join(r'\shortstack{'+label+r'\\$N='+str(cells[key]['n'])+r'$}' for key,label in strata) + r' \\',
        r'\midrule',
        'No memory & ' + ' & '.join(f"{cells[key]['conditions']['no_memory']['mean_similarity']:.2f}" for key,_ in strata) + r' \\',
        r'\midrule',
    ]
    for key,label in policies:
        lines.append(label + r' $\Delta$ & ' + ' & '.join(diff_cell(cells[stratum]['conditions'][key]['diff_vs_no_memory']['mean_similarity']) for stratum,_ in strata) + r' \\')
    lines += [r'\bottomrule',r'\end{tabular}',r'\end{table}']
    (TABLES/'trackb_main_identity.tex').write_text('\n'.join(lines)+'\n')
    print('Wrote',TABLES/'trackb_main_identity.tex')


if __name__ == '__main__':main()
