#!/usr/bin/env python3
"""Render a compact quality control from the frozen 2026-09-30 aggregate.

Complete six-metric, five-condition results remain in the supplementary table.
"""
import json
from pathlib import Path
from ci_format import ci_cell

T = Path(__file__).resolve().parents[1] / 'tables' / 'experiments'

def main():
    data = json.loads((T / 'trackb_quality_control.json').read_text())['shared_generator']
    rows = [('imaging_quality', 'Imaging'), ('aesthetic_quality', 'Aesthetic'),
            ('subject_consistency', 'Subject consistency'), ('background_consistency', 'Background consistency'),
            ('recall', 'Per-clip entity recall')]
    lines = [r'\begin{table}[t]', r'\centering',
        '% Generated by scripts/make_main_quality_table.py; do not edit by hand.',
        r'\caption{\textbf{Clip quality versus entity recall.} Same 2,824 clips per condition; means with story-bootstrap 95\% CIs; gray subscripts show full widths (upper minus lower). All metrics are higher-is-better. Intervals condition on one rollout per story. Complete conditions and six quality metrics: Supplementary Table~\ref{tab:quality-control}.}',
        r'\label{tab:main-quality}', r'\footnotesize', r'\setlength{\tabcolsep}{3pt}',
        r'\begin{tabular}{@{}lcc@{}}', r'\toprule', r'Metric & No memory & Seg+DINO-key \\', r'\midrule']
    for key, label in rows:
        cells = [data['memory_recall'][c] if key == 'recall' else data['per_condition'][c][key]
                 for c in ['no_memory', 'seg_dinokey']]
        lines.append(label + ' & ' + ' & '.join(ci_cell(f"{c['mean']:.3f}", f"{c['lo']:.3f}", f"{c['hi']:.3f}") for c in cells) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular}', r'\end{table}']
    (T / 'trackb_main_quality.tex').write_text('\n'.join(lines)+'\n')

if __name__ == '__main__':
    main()
