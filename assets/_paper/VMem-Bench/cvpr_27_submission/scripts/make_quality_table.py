#!/usr/bin/env python3
"""Render tables/experiments/trackb_quality_control.tex from the quality-control aggregate.

    python3 scripts/make_quality_table.py --aggregate <.../trackb_quality_control_*/aggregate/aggregate.json>

Mean with gray subscript widths for the story-clustered 95% CI; per column the best value is underlined (ties share the mark). Deterministic.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from ci_format import ci_cell

OUT = Path(__file__).resolve().parents[1] / "tables" / "experiments" / "trackb_quality_control.tex"
ROWS = [("text_frame", "Text-frame"), ("seg_uniform", "Seg+uniform"), ("seg_dinokey", "Seg+DINO-key"),
        ("seg_frame_clean", "Seg+frame"), ("no_memory", r"No memory ($K{=}0$)")]
COLS = [("imaging_quality", "Imaging", 3), ("aesthetic_quality", "Aesthetic", 3),
        ("subject_consistency", "Subj.\\ cons.", 3), ("background_consistency", "Bg.\\ cons.", 3),
        ("dynamic_degree", "Dynamic", 3), ("motion_smoothness", "Motion sm.", 4), ("recall", "Clip rec.", 3)]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--aggregate", type=Path, required=True)
    args = ap.parse_args()
    sg = json.loads(args.aggregate.read_text())["shared_generator"]
    cell = {}
    for key, _ in ROWS:
        for m, _, _ in COLS:
            cell[key, m] = sg["memory_recall"][key] if m == "recall" else sg["per_condition"][key][m]

    marks = {}
    for m, _, d in COLS:
        vals = sorted({round(cell[k, m]["mean"], d) for k, _ in ROWS}, reverse=True)
        for k, _ in ROWS:
            v = round(cell[k, m]["mean"], d)
            marks[k, m] = "bf" if v == vals[0] else ("ul" if len(vals) > 1 and v == vals[1] else "")

    def fmt(k: str, m: str, d: int) -> str:
        c = cell[k, m]
        return ci_cell(f"{c['mean']:.{d}f}", f"{c['lo']:.{d}f}", f"{c['hi']:.{d}f}", underline=marks[k, m] == "bf")

    lines = [
        f"% Generated by scripts/make_quality_table.py from {args.aggregate.name}; do not edit by hand.",
        "\\begin{tabular}{@{}l " + "c" * len(COLS) + "@{}}",
        "\\toprule",
        "Condition & " + " & ".join(f"{h}$\\uparrow$" for _, h, _ in COLS) + " \\\\",
        "\\midrule",
    ]
    for i, (k, label) in enumerate(ROWS):
        if k == "no_memory":
            lines.append("\\midrule")
        cells = [fmt(k, m, d) for m, _, d in COLS]
        lines.append(f"{label} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
