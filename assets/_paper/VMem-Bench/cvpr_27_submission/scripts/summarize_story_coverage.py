#!/usr/bin/env python3
"""Summarize existing evaluated story metadata; never runs a generator or scorer."""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import statistics

PAPER = Path(__file__).resolve().parents[1]
T = PAPER / 'tables' / 'experiments'
PROBES = [('lookalike_disambiguation', 'Look-alike'), ('state_change', 'State change'),
          ('persist_state', 'Persistent state'), ('count_memory', 'Count memory'),
          ('false_friend', 'False friend'), ('deprecation_avoidance', 'Deprecation avoidance'),
          ('reference_indirect', 'Indirect reference'), ('long_gap_reappearance', 'Long-gap return'),
          ('temporal_reference', 'Temporal reference')]


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--gold-root', type=Path, required=True)
    ap.add_argument('--prompts-root', type=Path, required=True)
    ap.add_argument('--reference-gold-root', type=Path)
    ap.add_argument('--reference-prompts-root', type=Path)
    args = ap.parse_args()
    cohort = json.loads((T / 'trackb_story_cohort.json').read_text())
    rows = []
    for story in cohort['stories']:
        g = args.gold_root / f'{story}.json'
        prompt = args.prompts_root / f'{story}_name_anchored.json'
        data = json.loads(g.read_text())
        if args.reference_gold_root:
            assert digest(g) == digest(args.reference_gold_root / g.name), story
        if args.reference_prompts_root:
            assert digest(prompt) == digest(args.reference_prompts_root / prompt.name), story
        counts = Counter(tag for seg in data['segments'] for tag in set(seg['memory_probes']))
        rows.append(dict(story_id=story, title=data['title'], segments=len(data['segments']),
                         duration_sec=sum(seg['duration_sec'] for seg in data['segments']),
                         entity_kinds=dict(Counter(e['kind'] for e in data['entities'].values())),
                         stateful_entities=sum(len(e.get('states', {})) > 1 for e in data['entities'].values()),
                         probe_segments={k: counts[k] for k, _ in PROBES},
                         gold_sha256=digest(g), prompts_sha256=digest(prompt)))
    lengths = [r['segments'] for r in rows]
    kinds = Counter()
    for r in rows:
        kinds.update(r['entity_kinds'])
    probes = {k: dict(segments=sum(r['probe_segments'][k] for r in rows),
                      stories=sum(r['probe_segments'][k] > 0 for r in rows),
                      min_per_story=min(r['probe_segments'][k] for r in rows),
                      max_per_story=max(r['probe_segments'][k] for r in rows)) for k, _ in PROBES}
    summary = dict(n_stories=len(rows), segments=sum(lengths), mean_segments=statistics.mean(lengths),
                   median_segments=statistics.median(lengths), min_segments=min(lengths), max_segments=max(lengths),
                   entity_kinds=dict(kinds), stateful_entities=sum(r['stateful_entities'] for r in rows),
                   duration_sec=sum(r['duration_sec'] for r in rows), probe_segments=probes)
    output = dict(cohort=cohort, summary=summary, stories=rows,
                  definitions={'probe_segments': 'Segment-level tags, counted once per family per segment; families can overlap. Not scored opportunities or observed successes.',
                               'stateful_entities': 'Story-local entity records with more than one defined appearance state.',
                               'genre': 'No genre labels or representativeness claims are inferred from story titles.'})
    (T / 'trackb_story_coverage.json').write_text(json.dumps(output, indent=2)+'\n')
    lines = [r'\begin{table*}[t]', r'\centering',
             '% Generated by scripts/summarize_story_coverage.py; do not edit by hand.',
             r'\caption{\textbf{Coverage of the evaluated Track-B cohort.} Only the 30 stories used in all six seed-2026 conditions are counted. Entity counts are story-local records. Right: tagged segments, number of stories containing the tag, and per-story count range. Tags overlap and are not scoring denominators or observed generation success rates.}',
             r'\label{tab:story-coverage}', r'\footnotesize',
             r'\begin{minipage}[t]{0.44\textwidth}\centering',
             r'\begin{tabular}{@{}lr@{}}\toprule', r'Cohort property & Value \\ \midrule',
             f"Stories / segments & {len(rows)} / {sum(lengths):,}"+r' \\',
             f"Segments: mean / median & {statistics.mean(lengths):.1f} / {statistics.median(lengths):g}"+r' \\',
             f"Segments: min--max & {min(lengths)}--{max(lengths)}"+r' \\',
             f"Scripted duration & {summary['duration_sec']/3600:.2f} h"+r' \\',
             *[f"{k.title()} entities & {kinds[k]}"+r' \\' for k in ['character','prop','location']],
             f"Entities with multiple states & {summary['stateful_entities']}"+r' \\',
             r'\bottomrule\end{tabular}\end{minipage}\hfill',
             r'\begin{minipage}[t]{0.54\textwidth}\centering',
             r'\begin{tabular}{@{}lrrr@{}}\toprule', r'Memory stress & Segments & Stories & Range \\ \midrule']
    for k, label in PROBES:
        q = probes[k]
        lines.append(f"{label} & {q['segments']} & {q['stories']} & {q['min_per_story']}--{q['max_per_story']}"+r' \\')
    lines += [r'\bottomrule\end{tabular}\end{minipage}', r'\end{table*}']
    (T / 'trackb_story_coverage.tex').write_text('\n'.join(lines)+'\n')
    print(json.dumps(summary, indent=2))


if __name__ == '__main__':
    main()
