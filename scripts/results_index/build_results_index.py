#!/usr/bin/env python3
"""Build the local, gitignored results/ index from a machine-local source table.

    python3 scripts/results_index/build_results_index.py [--results results] [--dry-run]

`<results>/sources.json` (not tracked; it holds machine-specific absolute paths) lists
entries of the form

    {"link": "trackB/shared_generator_testbed/text_frame",
     "target": "/abs/path/to/run/root",          # or null when the data is lost
     "status": "present" | "missing" | "in_progress" | "superseded",
     "paper": "which table/figure/claim uses it",
     "note": "free text",
     "expect": {"children": 30, "each_has": "name_anchored/<tag>/_trackB_score/score.json"}}

The script only creates/refreshes symlinks and never copies, moves, or deletes data.
File counts and byte sizes come from CephFS xattrs (ceph.dir.rfiles / ceph.dir.rbytes),
so no recursive walk is performed. `expect` checks stat at most one path per child.
Outputs: `<results>/inventory.json` and `<results>/INVENTORY.md` (both regenerated).
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def xattr_int(path: Path, name: str) -> int | None:
    try:
        return int(os.getxattr(path, name).decode().strip())
    except (OSError, ValueError):
        return None


def human(n: int | None) -> str:
    if n is None:
        return "-"
    for unit in ("B", "K", "M", "G", "T"):
        if n < 1024 or unit == "T":
            return f"{n:.0f}{unit}" if unit == "B" else f"{n:.1f}{unit}"
        n /= 1024
    return str(n)


def check_expect(target: Path, expect: dict) -> dict:
    kids = sorted(p for p in target.iterdir() if p.is_dir() and not p.name.startswith((".", "_")))
    out = {"children_found": len(kids), "children_expected": expect.get("children")}
    rel = expect.get("each_has")
    if rel:
        ok = 0
        for kid in kids:
            cur = [kid]
            for part in rel.split("/"):
                if part.startswith("<") and part.endswith(">"):
                    cur = [p for c in cur if c.is_dir() for p in c.iterdir() if p.is_dir()]
                else:
                    cur = [c / part for c in cur]
            ok += any(p.exists() for p in cur)
        out["each_has"] = rel
        out["children_with_file"] = ok
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--results", type=Path, default=ROOT / "results")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    res: Path = args.results
    entries = json.loads((res / "sources.json").read_text())["entries"]

    rows = []
    for e in entries:
        link = res / e["link"]
        target = Path(e["target"]) if e.get("target") else None
        row = {k: e.get(k) for k in ("link", "target", "status", "paper", "note")}
        row["exists"] = bool(target and target.exists())
        if target and not args.dry_run:
            link.parent.mkdir(parents=True, exist_ok=True)
            if link.is_symlink() or link.exists():
                if link.is_symlink():
                    link.unlink()
                else:
                    raise SystemExit(f"refusing to replace non-symlink {link}")
            link.symlink_to(target)
        if row["exists"]:
            if target.is_dir():
                row["rfiles"] = xattr_int(target, "ceph.dir.rfiles")
                row["rbytes"] = xattr_int(target, "ceph.dir.rbytes")
            else:
                row["rfiles"], row["rbytes"] = 1, target.stat().st_size
            if e.get("expect") and target.is_dir():
                row["expect"] = check_expect(target, e["expect"])
        rows.append(row)

    (res / "inventory.json").write_text(json.dumps({"entries": rows}, indent=2, ensure_ascii=False) + "\n")
    lines = [
        "# Inventory (generated by scripts/results_index/build_results_index.py; do not edit)",
        "",
        "| link | status | exists | files | size | check | paper use |",
        "|---|---|---|---:|---:|---|---|",
    ]
    for r in rows:
        chk = ""
        if "expect" in r:
            x = r["expect"]
            chk = f"{x['children_found']}/{x['children_expected']} dirs"
            if "children_with_file" in x:
                chk += f", {x['children_with_file']} with `{x['each_has'].split('/')[-1]}`"
        lines.append(
            f"| `{r['link']}` | {r['status']} | {'yes' if r['exists'] else 'NO'} | "
            f"{r.get('rfiles') if r.get('rfiles') is not None else '-'} | {human(r.get('rbytes'))} | "
            f"{chk} | {r.get('paper') or ''} |"
        )
    (res / "INVENTORY.md").write_text("\n".join(lines) + "\n")
    bad = [r["link"] for r in rows if r["status"] in ("present", "superseded") and not r["exists"]]
    print(f"{len(rows)} entries; {sum(r['exists'] for r in rows)} resolved; broken present-links: {bad or 'none'}")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
